def main(filepaths):
    for path in filepaths:
        print(f"Processing {path} …", file=sys.stderr)
        doc = udapi.Document(path)
        fixed = 0
        for bundle in doc.bundles:
            for tree in bundle.trees:
                before = tree.sent_id
                fix_tree(tree)
                fixed += 1
        doc.store_conllu(path)
        print(f"  Done ({fixed} sentences processed)", file=sys.stderr)


if __name__ == '__main__':
    if len(sys.argv) < 2:
        print("Usage: python fix_too_many_subjects.py file1.conllu [file2.conllu ...]")
        sys.exit(1)
    main(sys.argv[1:])
